#!/usr/bin/env node
/**
 * sync-game-i18n.mjs - genere lib/i18n/translations/games-map.ts
 *
 * Source de verite : les fichiers lib/i18n/translations/games/<jeu>/{en,fr}.json.
 * Le namespace de chaque jeu est la cle racine de son JSON. Les namespaces qui
 * n ont pas encore de dossier JSON (ex. timeclone) sont conserves tels quels :
 * le script ne perd jamais une traduction deja presente.
 *
 * Usage :
 *   node scripts/sync-game-i18n.mjs            ecrit le fichier
 *   node scripts/sync-game-i18n.mjs --check    n ecrit rien, sort 1 si desynchronise
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib", "i18n", "translations", "games-map.ts");
const SRC_DIR = join(ROOT, "lib", "i18n", "translations", "games");
const checkOnly = process.argv.includes("--check");

const HEADER = [
  "// Auto-generated game translations map - regenerated by scripts/sync-game-i18n.mjs",
  "// DO NOT EDIT MANUALLY",
  "",
].join("\n");

function formatValue(value, indent) {
  const pad = " ".repeat(indent);
  if (value === null || typeof value !== "object") {return JSON.stringify(value);}
  const keys = Object.keys(value);
  if (keys.length === 0) {return "{}";}
  const allPrimitive = keys.every((k) => value[k] === null || typeof value[k] !== "object");
  if (allPrimitive) {
    const inline = `{ ${keys.map((k) => `${JSON.stringify(k)}: ${JSON.stringify(value[k])}`).join(", ")} }`;
    // N inline que si la ligne reste courte (comme prettier, largeur 100).
    if (indent + inline.length <= 100) {return inline;}
  }
  const inner = keys.map((k) => `${pad}  ${JSON.stringify(k)}: ${formatValue(value[k], indent + 2)}`).join(",\n");
  return `{\n${inner}\n${pad}}`;
}

function formatGamesMap(map) {
  const block = (name, obj) =>
    `const ${name} = {\n` +
    Object.keys(obj).map((k) => `  ${JSON.stringify(k)}: ${formatValue(obj[k], 2)}`).join(",\n") +
    "\n};";
  return (
    HEADER +
    "\n" +
    block("enGames", map.en) +
    "\n\n" +
    block("frGames", map.fr) +
    "\n\n" +
    "export const gameTranslations: Record<'en' | 'fr', Record<string, any>> = {\n" +
    "  en: enGames,\n" +
    "  fr: frGames,\n" +
    "};\n"
  );
}

// 1) Charger la map existante (source de verite des namespaces sans JSON).
const existing = (await import(pathToFileURL(OUT).href)).gameTranslations;
const merged = { en: { ...existing.en }, fr: { ...existing.fr } };

// 2) Fusionner chaque dossier JSON, sans jamais retirer un namespace existant.
const dirs = readdirSync(SRC_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && statSync(join(SRC_DIR, d.name)).isDirectory())
  .map((d) => d.name)
  .sort();

let added = 0;
let updated = 0;
for (const dir of dirs) {
  for (const locale of ["en", "fr"]) {
    const file = join(SRC_DIR, dir, `${locale}.json`);
    let parsed;
    try { parsed = JSON.parse(readFileSync(file, "utf8")); } catch { continue; }
    for (const [namespace, value] of Object.entries(parsed)) {
      const before = merged[locale][namespace];
      if (before === undefined) {added++;}
      else if (JSON.stringify(before) !== JSON.stringify(value)) {updated++;}
      merged[locale][namespace] = value;
    }
  }
}

// 3) Ecrire, ou verifier.
const next = formatGamesMap(merged);
const current = readFileSync(OUT, "utf8");
const inSync = current === next;

if (checkOnly) {
  if (!inSync) {
    console.error("games-map.ts desynchronise : lancer `node scripts/sync-game-i18n.mjs`.");
    process.exit(1);
  }
  console.log(`games-map.ts synchronise (${dirs.length} dossiers JSON, ${Object.keys(merged.en).length} namespaces).`);
  process.exit(0);
}

if (inSync) {
  console.log("games-map.ts deja a jour.");
} else {
  writeFileSync(OUT, next, "utf8");
  console.log(`games-map.ts ecrit (${added} entree(s) ajoutee(s), ${updated} mise(s) a jour, ${Object.keys(merged.en).length} namespaces).`);
}
